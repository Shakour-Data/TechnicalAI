/**
 * Deterministic seeded shuffle using Fisher-Yates.
 */
function seededShuffle<T>(array: T[], seed: number): T[] {
  const result = [...array];
  let s = seed;
  for (let i = result.length - 1; i > 0; i--) {
    s = (s * 1664525 + 1013904223) & 0xffffffff;
    const j = s % (i + 1);
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

/**
 * Get `count` phrases from a section/subcategory, deterministically shuffled by seed.
 * Returns fewer phrases if the subcategory doesn't have enough.
 */
export function getPhrases(section: string, subcategory: string, seed: number, count: number): string[] {
  const sec = PHRASE_BANK[section];
  if (!sec) return [];
  const phrases = sec.phrases[subcategory];
  if (!phrases || phrases.length === 0) return [];
  const shuffled = seededShuffle(phrases, seed);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
